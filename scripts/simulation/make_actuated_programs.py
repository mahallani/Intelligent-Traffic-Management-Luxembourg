"""Create sumo/lust_4_intersections/additional/tls_actuated_v1.add.xml: SUMO's built-in actuated
control (gap-based, automatic detectors) on the SAME phase sequence and yellow times as the LuST
programs. Green phases: minDur = 5 s, maxDur = 2 x programmed duration. Refuses to overwrite."""
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
NET = ROOT / "sumo/lust_4_intersections/net/kirchberg_4tls.net.xml"
OUT = ROOT / "sumo/lust_4_intersections/additional/tls_actuated_v1.add.xml"


def main():
    if OUT.exists():
        print(f"{OUT} exists - not overwritten"); return 0
    root = ET.Element("additional")
    root.append(ET.Comment(" generated by scripts/simulation/make_actuated_programs.py from kirchberg_4tls.net.xml "))
    for tl in ET.parse(NET).getroot().iter("tlLogic"):
        new = ET.SubElement(root, "tlLogic", id=tl.get("id"), type="actuated", programID="actuated_v1", offset="0")
        for ph in tl.iter("phase"):
            st, d = ph.get("state"), float(ph.get("duration"))
            attrs = {"duration": f"{d:g}", "state": st}
            if ("G" in st or "g" in st) and "y" not in st:
                attrs.update(minDur="5", maxDur=f"{2 * d:g}")
            ET.SubElement(new, "phase", attrs)
    ET.indent(root)
    ET.ElementTree(root).write(OUT, encoding="UTF-8", xml_declaration=True)
    print("written", OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
